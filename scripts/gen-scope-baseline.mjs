// production 스키마 지문(schema-fingerprint.sql 결과, 읽기 전용)에서 "복원(백업) 범위 테이블(핵심 16 + 전체 시스템 추가 7)"의 baseline DDL 을 생성한다.
//   node scripts/gen-scope-baseline.mjs <fp-prod.json> > scripts/staging/production-baseline-scope.sql
// 생성물은 staging 전용: 범위 테이블을 DROP ... CASCADE 후 production 과 같은 컬럼/제약/인덱스/트리거로 재생성한다(데이터 없음).
// 그 위에 pending migration 들을 순서대로 적용하면 "production 이 migration 을 적용한 뒤의 스키마"와 같은 staging 이 된다.
import { readFileSync } from 'node:fs'
import { BASELINE_SCOPE as SCOPE } from './schema-diff-scope.mjs'

const t = readFileSync(process.argv[2], 'utf8')
const prod = JSON.parse(t.slice(t.indexOf('{'))).rows[0].jsonb_build_object
const q = (s) => `"${s}"`
const out = []
out.push('-- STAGING TEST ONLY — NEVER APPLY TO PRODUCTION. production 스키마에서 생성(gen-scope-baseline.mjs), 데이터 없음.')
out.push('-- 범위 테이블을 지우고 production 과 같은 구조로 다시 만든다. (staging guard 통과 후에만 실행)')
out.push('create or replace function public.update_updated_at()\n returns trigger\n language plpgsql\nas $fn$\nbegin\n  new.updated_at = now();\n  return new;\nend;\n$fn$;')
out.push(`drop table if exists ${SCOPE.map(x => 'public.' + q(x)).join(', ')} cascade;`)
const fks = []
for (const name of SCOPE) {
  const T = prod.tables[name]
  if (!T) throw new Error('production 에 없는 범위 테이블: ' + name)
  const seqs = []
  const cols = T.columns.map(c => {
    let line = `  ${q(c.name)} ${c.type}`
    if (c.identity === 'd') line += ' generated by default as identity'
    else if (c.identity === 'a') line += ' generated always as identity'
    else if (c.default) {
      line += ` default ${c.default}`
      const m = /^nextval\('([^']+)'::regclass\)$/.exec(c.default)
      if (m) seqs.push([m[1], c.name])
    }
    if (c.notnull) line += ' not null'
    return line
  })
  const cons = T.constraints.filter(k => k.type !== 'f').map(k => `  constraint ${q(k.name)} ${k.def}`)
  for (const [s] of seqs) out.push(`create sequence if not exists public.${s.replace(/^public\./, '')};`)
  out.push(`create table public.${q(name)} (\n${[...cols, ...cons].join(',\n')}\n);`)
  for (const [s, col] of seqs) out.push(`alter sequence public.${s.replace(/^public\./, '')} owned by public.${q(name)}.${q(col)};`)
  for (const k of T.constraints.filter(k => k.type === 'f')) fks.push(`alter table public.${q(name)} add constraint ${q(k.name)} ${k.def};`)
  // 인덱스: PK/UNIQUE 제약이 이미 만든 인덱스는 건너뛴다
  const uniqCols = new Set(T.constraints.filter(k => k.type === 'p' || k.type === 'u').map(k => /\(([^)]*)\)/.exec(k.def)?.[1]?.replace(/\s/g, '')))
  T.indexes.forEach((ix, i) => {
    const norm = typeof ix === 'string' ? ix : ix.norm
    const m = /^CREATE UNIQUE INDEX ON [^ ]+ USING btree \(([^)]*)\)$/.exec(norm)
    if (m && uniqCols.has(m[1].replace(/\s/g, ''))) return
    out.push(norm.replace(/^CREATE (UNIQUE )?INDEX ON/, (_, u) => `create ${u || ''}index if not exists ${q(`${name}_pi${i}_idx`)} on`) + ';')
  })
  T.triggers.forEach((tr, i) => {
    const norm = typeof tr === 'string' ? tr : tr.norm
    out.push(norm.replace(/^TRIGGER/, `create trigger ${q(`${name}_pt${i}`)}`) + ';')
  })
  if (T.rls) out.push(`alter table public.${q(name)} enable row level security;`)
}
out.push('-- FK (범위 안 테이블끼리 + production FK 그대로)')
out.push(...fks)
// 범위 밖 테이블이 범위 안 테이블을 참조하는 production FK 도 복구(DROP CASCADE 로 사라짐)
out.push('-- 범위 밖 테이블 → 범위 안 테이블 FK 복구(테이블이 있을 때만)')
for (const [name, T] of Object.entries(prod.tables)) {
  if (SCOPE.includes(name)) continue
  for (const k of T.constraints.filter(k => k.type === 'f' && SCOPE.some(s => new RegExp(`REFERENCES ${s}\\(`).test(k.def)))) {
    const cols = /FOREIGN KEY \(([^)]*)\)/.exec(k.def)[1].split(',').map(x => x.trim().replace(/"/g, ''))
    const colCond = cols.map(c => `exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = '${name}' and column_name = '${c}')`).join(' and ')
    out.push(`do $$ begin if to_regclass('public.${name}') is not null and ${colCond} and not exists (select 1 from pg_constraint where conname = '${k.name}' and conrelid = 'public.${name}'::regclass) then alter table public.${q(name)} add constraint ${q(k.name)} ${k.def}; end if; end $$;`)
  }
}
console.log(out.join('\n'))
