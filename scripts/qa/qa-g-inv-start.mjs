// QA G1 — 관리자가 실제 UI(정상 workflow)로 QA 실사 세션 시작 (service_role/직접 SQL 사용 안 함)
import { browserLaunch, session, ok, note, summary, shot, overflowX, adminLogin, BASE } from './lib.mjs'
const LABEL = process.env.QA_SESSION_LABEL || 'QA_FINAL_INVENTORY_20260921'
const browser = await browserLaunch(false)
const { ctx, page, rec } = await session(browser, { w: 1440, h: 900 })
await page.goto(BASE + '/', { waitUntil: 'domcontentloaded' })
await adminLogin(page)
await page.goto(BASE + '/inventory', { waitUntil: 'domcontentloaded' })
await page.getByRole('button', { name: /실사 시작/ }).waitFor({ timeout: 20000 })
ok('STEP3 admin sees "진행 중인 실사 없음" + 🚀 실사 시작 (no active session yet)', (await page.locator('main').innerText()).includes('진행 중인 실사 없음'))
await page.getByRole('button', { name: /실사 시작/ }).click()
const modal = page.locator('div', { has: page.locator('h3', { hasText: '실사 시작' }) }).last()
await page.getByPlaceholder('예: 1학기, 여름방학, 3층 점검').fill(LABEL)
await page.getByRole('button', { name: /현재목록 재고실사/ }).click()
await page.getByRole('button', { name: '구역 선택', exact: true }).click()
await page.getByRole('button', { name: 'QA-FINAL-실사실', exact: true }).click()
await shot(page, 'G1-start-modal-filled')
await page.getByRole('button', { name: '시작', exact: true }).click()
await page.waitForFunction(() => document.body.innerText.includes('QA_FINAL_INVENTORY'), null, { timeout: 20000 })
await page.waitForTimeout(800)
const dlg = (rec.dialogs || []).map(d => d.msg)
ok('STEP3 session started through the normal admin UI → server RPC inventory_session_start (alert: 총 3개 Lot)', dlg.some(m => m.includes('실사가 시작되었습니다') && m.includes('3개 Lot')), dlg)
const t = await page.locator('main').innerText()
ok('STEP3 active session card: label, mode 현재목록 재고실사, scope QA-FINAL-실사실, progress 0 / 3', t.includes(LABEL) && t.includes('현재목록 재고실사') && t.includes('QA-FINAL-실사실') && t.includes('0 / 3개 완료'), t.slice(0, 300).replace(/\n/g, ' | '))
await shot(page, 'G1-session-active-admin')
ok('STEP3 admin controls present: ⏸ 일시중단 / 🗑️ 실사 취소 / ✅ 실사 완료 처리', (await page.getByRole('button', { name: /일시중단/ }).count()) === 1 && (await page.getByRole('button', { name: /실사 완료 처리/ }).count()) === 1)
ok('console clean / no production', rec.errors.length === 0 && rec.console.filter(c => c.t === 'error').length === 0 && rec.prod.length === 0, { c: rec.console.slice(0, 3) })
await ctx.close(); await browser.close()
summary()
